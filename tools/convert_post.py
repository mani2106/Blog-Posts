import re
import pathlib
import posixpath

DROP_KEYS = {"layout", "keywords", "toc", "branch", "badges", "comments", "hide", "nb_path"}
DATE_RE = re.compile(r"^(\d{4}-\d{2}-\d{2})")

def _strip_fences(raw_yaml: str) -> str:
    lines = raw_yaml.strip().splitlines()
    if lines and lines[0].strip() == "---":
        lines = lines[1:]
    if lines and lines[-1].strip() == "---":
        lines = lines[:-1]
    return "\n".join(lines)

def convert_frontmatter(raw_yaml: str, filename: str) -> str:
    import yaml
    body = _strip_fences(raw_yaml)
    data = yaml.safe_load(body) or {}
    m = DATE_RE.match(pathlib.Path(filename).name)
    if m:
        data.setdefault("date", m.group(1))
    if "summary" in data and "description" not in data:
        data["description"] = data.pop("summary")
    elif "summary" in data:
        data.pop("summary", None)
    for k in DROP_KEYS:
        data.pop(k, None)
    out = yaml.safe_dump(data, sort_keys=False, allow_unicode=True).strip()
    return out

# Module-level regexes
BANNER_RE = re.compile(r"<!--\s*THIS FILE WAS AUTOGENERATED!.*?-->", re.IGNORECASE)
BASEURL = "/Blog-Posts"
IMAGE_INCLUDE_RE = re.compile(
    r"\{%\s*include\s+image\.html\s+(?P<args>.*?)\s*%\}",
    re.DOTALL,
)
RELURL_RE = re.compile(r"\{\{\s*['\"](?P<p>[^'\"]+)['\"]\s*\|\s*relative_url\s*\}\}")

def _parse_kv(args: str) -> dict:
    kv = {}
    for m in re.finditer(r'(?P<k>\w+)\s*=\s*"(?P<v>.*?)"', args):
        kv[m.group("k")] = m.group("v")
    return kv

def _resolve_path(p: str) -> str:
    p = p.strip()
    if p.startswith(BASEURL):
        p = p[len(BASEURL):]
    return posixpath.normpath(p)   # keep leading "/" -> Quarto project-root-relative (posts live in posts/<slug>/)

def _image_include_repl(match: re.Match) -> str:
    kv = _parse_kv(match.group("args"))
    src = _resolve_path(kv.get("file", ""))
    caption = kv.get("caption") or kv.get("alt") or ""
    return f"![{caption}]({src})"

def convert_body(md: str) -> str:
    md = BANNER_RE.sub("", md)
    md = RELURL_RE.sub(lambda m: _resolve_path(m.group("p")), md)
    md = IMAGE_INCLUDE_RE.sub(_image_include_repl, md)
    return md.strip() + "\n"

def convert(input_path: pathlib.Path, output_path: pathlib.Path) -> None:
    text = input_path.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n?(.*)$", text, re.DOTALL)
    if not m:
        fm, body = "", text
    else:
        fm, body = "---\n" + m.group(1) + "\n---", m.group(2)
    fm = convert_frontmatter(fm, input_path.name)
    body = convert_body(body)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(f"---\n{fm}\n---\n\n{body}", encoding="utf-8")
