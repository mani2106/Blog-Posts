import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from convert_post import convert_frontmatter, convert_body

def _yaml_scalar_pairs(text):
    """Map each top-level 'key: value' line to {key: value}, skipping
    block-list items. Robust to PyYAML's quote/flow-style choices."""
    pairs = {}
    for line in text.splitlines():
        if line and not line.startswith((" ", "\t", "-")) and ":" in line:
            k, _, v = line.partition(":")
            pairs[k.strip()] = v.strip()
    return pairs

def test_drops_fastpages_keys_and_maps_summary():
    raw = """---
title: "My Post"
layout: post
keywords: a, b
toc: true
branch: master
badges: true
comments: true
categories: [azure, ai]
hide: false
summary: "Real summary"
image: images/azure/d.png
---"""
    out = convert_frontmatter(raw, "2025-11-17-azure-post.md")
    pairs = _yaml_scalar_pairs(out)
    for bad in ("layout", "keywords", "toc", "branch", "badges", "comments", "hide", "nb_path", "summary"):
        assert bad not in pairs, f"{bad!r} should be dropped; output was:\n{out}"
    assert pairs.get("title") == "My Post"
    assert "azure" in out and "ai" in out                    # categories preserved (style-agnostic)
    assert "2025-11-17" in pairs.get("date", "")             # date pulled from filename
    assert "Real summary" in pairs.get("description", "")    # summary -> description
    assert pairs.get("image") == "images/azure/d.png"

def test_date_pulled_from_filename_when_absent():
    raw = '---\ntitle: "X"\n---'
    out = convert_frontmatter(raw, "2019-06-01-Fast_ai_lesson_2.md")
    assert "2019-06-01" in out

def test_strips_autogen_banner():
    md = '<!-- THIS FILE WAS AUTOGENERATED! DO NOT EDIT! -->\n\nHello.'
    assert "AUTOGENERATED" not in convert_body(md)
    assert "Hello." in convert_body(md)

def test_image_include_to_markdown_and_normalizes_path():
    md = '<p>{% include image.html file="/Blog-Posts/images/copied_from_nb/../images/manhattan.png" caption="Manhattan" %}</p>'
    out = convert_body(md)
    assert "<p>{% include" not in out
    # baseurl stripped and .. collapsed
    assert "/Blog-Posts/" not in out
    assert "copied_from_nb/.." not in out
    assert "/images/images/manhattan.png" in out
    assert "![Manhattan](" in out

def test_relative_url_filter_strips_baseurl():
    md = "See [x]({{ '/assets/y.css' | relative_url }})."
    out = convert_body(md)
    assert "relative_url" not in out
    assert "/Blog-Posts" not in out
    assert "/assets/y.css" in out

# run all
def _run_all():
    test_drops_fastpages_keys_and_maps_summary()
    test_date_pulled_from_filename_when_absent()
    test_strips_autogen_banner()
    test_image_include_to_markdown_and_normalizes_path()
    test_relative_url_filter_strips_baseurl()
    print("OK")

if __name__ == "__main__":
    _run_all()
